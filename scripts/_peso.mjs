// Peso da primeira visita (bytes transferidos até a cena ficar pronta) e do momento de entrar num apartamento.
import { chromium } from "playwright";
const [base] = process.argv.slice(2);
const browser = await chromium.launch({ args: ["--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"] });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
const page = await ctx.newPage();
const cdp = await ctx.newCDPSession(page);
await cdp.send("Network.enable");
let reg = [];
const urls = new Map();
cdp.on("Network.responseReceived", (e) => urls.set(e.requestId, e.response.url));
cdp.on("Network.loadingFinished", (e) => reg.push([urls.get(e.requestId) ?? "?", e.encodedDataLength]));
const resumo = (titulo) => {
  const tipo = (u) => (/\.js/.test(u) ? "js" : /\.(jpg|png|webp|avif)|_next\/image/.test(u) ? "imagens" : /\.glb/.test(u) ? "modelos" : /\.(woff2?|ttf)/.test(u) ? "fontes" : /\.css/.test(u) ? "css" : "outros");
  const m = {};
  for (const [u, b] of reg) m[tipo(u)] = (m[tipo(u)] ?? 0) + b;
  const total = reg.reduce((s, [, b]) => s + b, 0);
  console.log(titulo, `${Math.round(total / 1024)} KB em ${reg.length} arquivos`, JSON.stringify(Object.fromEntries(Object.entries(m).map(([k, v]) => [k, Math.round(v / 1024)]))));
  console.log("  maiores:", reg.sort((a, b) => b[1] - a[1]).slice(0, 5).map(([u, b]) => `${u.split("/").pop().split("?")[0].slice(0, 26)} ${Math.round(b / 1024)}`).join(" | "));
  reg = [];
};
const t0 = Date.now();
await page.goto(base + "/?debug=1&unidade=1301");
await page.waitForFunction(() => window.__zp?.getState().pronto === true, null, { timeout: 240000 });
console.log(`pronto em ${((Date.now() - t0) / 1000).toFixed(1)} s`);
await page.waitForTimeout(4000);
resumo("primeira visita:");
await page.evaluate(() => window.__zp.getState().pularIntro());
await page.waitForFunction(() => { const s = window.__zp.getState(); return s.estado === "UNIDADE" && !s.emVoo; }, null, { timeout: 120000 });
await page.waitForTimeout(5000);
resumo("ao selecionar a unidade (pré-carregamento):");
const t1 = Date.now();
await page.evaluate(() => window.__zp.getState().entrar());
await page.waitForFunction(() => { const s = window.__zp.getState(); return s.estado === "PASSEIO" && !s.emVoo && !s.veu; }, null, { timeout: 120000 });
await page.waitForFunction(() => (window.__cena.getObjectByName("moveis_glb")?.children.length ?? 0) >= 10, null, { timeout: 120000 });
console.log(`dentro do apartamento, com os móveis, em ${((Date.now() - t1) / 1000).toFixed(1)} s`);
await page.waitForTimeout(3000);
resumo("ao entrar no apartamento:");
await browser.close();
